CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 username VARCHAR(24) NOT NULL UNIQUE,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 display_name VARCHAR(80) NOT NULL,
 bio TEXT NOT NULL,
 location VARCHAR(100) NOT NULL DEFAULT '',
 website VARCHAR(1000) NOT NULL DEFAULT '',
 now_text TEXT NOT NULL,
 uses_text TEXT NOT NULL,
 theme VARCHAR(20) NOT NULL DEFAULT 'cedar',
 listed INTEGER NOT NULL DEFAULT 1,
 role VARCHAR(20) NOT NULL DEFAULT 'member',
 suspended INTEGER NOT NULL DEFAULT 0,
 auth_version INTEGER NOT NULL DEFAULT 1,
 created_at VARCHAR(30) NOT NULL,
 updated_at VARCHAR(30) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS entries (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT NOT NULL,
 kind VARCHAR(20) NOT NULL,
 slug VARCHAR(80) NOT NULL,
 title VARCHAR(160) NOT NULL,
 body TEXT NOT NULL,
 target_url VARCHAR(2000) NOT NULL DEFAULT '',
 tags VARCHAR(250) NOT NULL DEFAULT '',
 visibility VARCHAR(20) NOT NULL DEFAULT 'private',
 created_at VARCHAR(30) NOT NULL,
 updated_at VARCHAR(30) NOT NULL,
 UNIQUE(user_id, slug),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS directory (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT NOT NULL,
 name VARCHAR(120) NOT NULL,
 category VARCHAR(30) NOT NULL,
 province VARCHAR(30) NOT NULL,
 website VARCHAR(2000) NOT NULL,
 claim VARCHAR(40) NOT NULL,
 evidence_url VARCHAR(2000) NOT NULL,
 notes TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 reviewed_at VARCHAR(30) NOT NULL DEFAULT '',
 created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS guestbook (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 owner_id BIGINT NOT NULL,
 author_id BIGINT NOT NULL,
 body TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (author_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS api_tokens (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT NOT NULL,
 token_hash VARCHAR(64) NOT NULL UNIQUE,
 created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS reports (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT NOT NULL,
 path VARCHAR(500) NOT NULL,
 reason TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'open',
 created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket VARCHAR(64) PRIMARY KEY,
 hits INTEGER NOT NULL,
 expires_at BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
